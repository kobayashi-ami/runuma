// 舞台: 左にCPUロボット、まんなかに共有のエレベーター、右に鏡写しのGPUロボット
//   CPUの層はフレームをそのまま x=0.. に置く。GPUの層は左右反転して x = kStageW-1-c に置く。
//   フレームの箱は x=16-27 なので、反転しても同じ場所に重なり、二体が同じ箱を使う。
static const int kStageW = 44;

typedef const char *const *Rows; // 1フレーム分（kFrameH 行）

// X=文字色（CPUロボットと箱）、S/G/R=GPUロボットの銀・緑・赤。暗いバーと明るいバーで色を変える
static NSColor *inkFor(char ch, BOOL dark) {
    switch (ch) {
        case 'X': return dark ? [NSColor colorWithWhite:0.93 alpha:1] : [NSColor colorWithWhite:0.08 alpha:1];
        case 'S': return dark ? [NSColor colorWithSRGBRed:0.77 green:0.79 blue:0.82 alpha:1]
                              : [NSColor colorWithSRGBRed:0.50 green:0.53 blue:0.56 alpha:1];
        case 'G': return dark ? [NSColor colorWithSRGBRed:0.18 green:0.80 blue:0.36 alpha:1]
                              : [NSColor colorWithSRGBRed:0.09 green:0.63 blue:0.25 alpha:1];
        case 'R': return dark ? [NSColor colorWithSRGBRed:1.00 green:0.19 blue:0.19 alpha:1]
                              : [NSColor colorWithSRGBRed:0.88 green:0.12 blue:0.12 alpha:1];
        default:  return nil;
    }
}

// GPUロボットがカラーなので、テンプレート画像（単色に自動着色）はやめて自前で色を塗る
static NSImage *stageImage(Rows cpu, Rows gpu, BOOL dark) {
    NSImage *img = [NSImage imageWithSize:NSMakeSize(kStageW, kFrameH)
                                  flipped:YES
                           drawingHandler:^BOOL(NSRect rect) {
        for (int r = 0; r < kFrameH; r++)
            for (int c = 0; c < kFrameW; c++) {
                NSColor *ink = inkFor(cpu[r][c], dark);
                if (ink) { [ink setFill]; NSRectFill(NSMakeRect(c, r, 1, 1)); }
                ink = inkFor(gpu[r][c], dark);
                if (ink) { [ink setFill]; NSRectFill(NSMakeRect(kStageW - 1 - c, r, 1, 1)); }
            }
        return YES;
    }];
    return img;
}

// GPU使用率: IOAccelerator の PerformanceStatistics → "Device Utilization %"（sudo不要）
static double readGpuUtilization(void) {
    io_iterator_t it;
    if (IOServiceGetMatchingServices(kIOMainPortDefault, IOServiceMatching("IOAccelerator"),
                                     &it) != KERN_SUCCESS)
        return -1;
    double best = -1;
    io_object_t svc;
    while ((svc = IOIteratorNext(it))) {
        CFTypeRef stats = IORegistryEntryCreateCFProperty(svc, CFSTR("PerformanceStatistics"),
                                                          kCFAllocatorDefault, 0);
        if (stats) {
            NSDictionary *d = CFBridgingRelease(stats);
            if ([d isKindOfClass:[NSDictionary class]]) {
                NSNumber *u = d[@"Device Utilization %"];
                if ([u isKindOfClass:[NSNumber class]] && u.doubleValue > best)
                    best = u.doubleValue;
            }
        }
        IOObjectRelease(svc);
    }
    IOObjectRelease(it);
    return best < 0 ? -1 : best / 100.0;
}

